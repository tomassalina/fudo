/** Active menu items for a merchant, in fixture order (already grouped by `section` upstream). */
export function getMenuItemsForMerchant(merchantId: number): MenuItem[] {
  return MOCK_MENU_ITEMS.filter(
    (item) => item.merchant_id === merchantId && item.active,
  );
}

/** Groups a merchant's menu items by their `section`, preserving first-seen section order. */
export function groupMenuItemsBySection(
  items: MenuItem[],
): { section: string; items: MenuItem[] }[] {
  const order: string[] = [];
  const bySection = new Map<string, MenuItem[]>();

  for (const item of items) {
    if (!bySection.has(item.section)) {
      order.push(item.section);
      bySection.set(item.section, []);
    }
    bySection.get(item.section)!.push(item);
  }

  return order.map((section) => ({ section, items: bySection.get(section)! }));
}
